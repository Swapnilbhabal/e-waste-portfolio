    (function topo() {
        const svg = $("#topo");
        if (!svg) return;
        svg.setAttribute("viewBox", "0 0 1440 900");
        // smooth closed curve through points (Catmull-Rom -> Bezier)
        const smooth = (pts) => {
            let d = `M${pts[0][0].toFixed(1)},${pts[0][1].toFixed(1)}`;
            for (let i = 0; i < pts.length; i++) {
                const p0 = pts[(i - 1 + pts.length) % pts.length], p1 = pts[i], p2 = pts[(i + 1) % pts.length], p3 = pts[(i + 2) % pts.length];
                d += ` C${(p1[0] + (p2[0] - p0[0]) / 6).toFixed(1)},${(p1[1] + (p2[1] - p0[1]) / 6).toFixed(1)} ${(p2[0] - (p3[0] - p1[0]) / 6).toFixed(1)},${(p2[1] - (p3[1] - p1[1]) / 6).toFixed(1)} ${p2[0].toFixed(1)},${p2[1].toFixed(1)}`;
            }
            return d + "Z";
        };
        const hills = [[1240, 140, 11, 34, 1.3], [170, 760, 10, 30, 2.1], [760, 470, 6, 40, 0.4]];
        let out = "";
        hills.forEach(([cx, cy, rings, gap, seedA]) => {
            for (let k = 1; k <= rings; k++) {
                const r = k * gap, pts = [];
                for (let a = 0; a < 48; a++) {
                    const t = (a / 48) * Math.PI * 2;
                    const wob = 1 + 0.16 * Math.sin(3 * t + seedA + k * 0.25) + 0.09 * Math.sin(5 * t - seedA * 2 + k * 0.4) + 0.05 * Math.sin(9 * t + k);
                    pts.push([cx + Math.cos(t) * r * wob * 1.25, cy + Math.sin(t) * r * wob]);
                }
                out += `<path d="${smooth(pts)}" style="opacity:${(1 - k / (rings + 3)).toFixed(2)}"/>`;
            }
        });
        svg.innerHTML = out;
    })();

    (function ambient() {
        const cv = $("#ambient");
        if (!cv || reduceMotion) return;
        const ctx = cv.getContext("2d");
        let W = 0, H = 0, dpr = 1, parts = [];
        const LEAF_COLORS = ["#5aa877", "#8fc25a", "#cf8d4a", "#77b79c", "#a9cf6f"];
        function resize() {
            dpr = Math.min(2, devicePixelRatio || 1);
            W = cv.width = Math.round(innerWidth * dpr);
            H = cv.height = Math.round(innerHeight * dpr);
        }
        function spawn(randomY) {
            return {
                x: Math.random() * W, y: randomY ? Math.random() * H : -20 * dpr,
                s: (0.8 + Math.random() * 0.7) * dpr,
                vx: (Math.random() - 0.5) * 0.3 * dpr, vy: (0.25 + Math.random() * 0.45) * dpr,
                rot: Math.random() * Math.PI * 2, vr: (Math.random() - 0.5) * 0.015,
                ph: Math.random() * Math.PI * 2, sp: 0.6 + Math.random() * 1.4,
                c: LEAF_COLORS[(Math.random() * LEAF_COLORS.length) | 0]
            };
        }
        resize();
        const count = innerWidth < 700 ? 12 : 26;
        for (let i = 0; i < count; i++) parts.push(spawn(true));
        addEventListener("resize", resize);

        function leaf(p, t) {
            const sway = Math.sin(t * 0.0011 * p.sp + p.ph);
            p.x += p.vx + sway * 0.35 * dpr;
            p.y += p.vy;
            p.rot += p.vr + sway * 0.004;
            if (p.y > H + 30 * dpr) Object.assign(p, spawn(false));
            if (p.x < -30) p.x = W + 20; if (p.x > W + 30) p.x = -20;
            const L = 12.5 * p.s;                      // leaf half-length (a little bigger than before)
            const flip = 0.55 + 0.45 * Math.abs(Math.cos(t * 0.0009 * p.sp + p.ph)); // gentle 3D flutter
            ctx.save();
            ctx.translate(p.x, p.y);
            ctx.rotate(p.rot);
            ctx.scale(1, flip);
            // body
            ctx.globalAlpha = 0.62;
            ctx.fillStyle = p.c;
            ctx.beginPath();
            ctx.moveTo(-L, 0);
            ctx.quadraticCurveTo(0, -L * 0.62, L, 0);
            ctx.quadraticCurveTo(0, L * 0.62, -L, 0);
            ctx.fill();
            // darker half for depth
            ctx.globalAlpha = 0.18;
            ctx.fillStyle = "#1d5a38";
            ctx.beginPath();
            ctx.moveTo(-L, 0);
            ctx.quadraticCurveTo(0, L * 0.62, L, 0);
            ctx.closePath();
            ctx.fill();
            // vein + small stem
            ctx.globalAlpha = 0.55;
            ctx.strokeStyle = "#2f6b45";
            ctx.lineWidth = 0.9 * dpr;
            ctx.beginPath(); ctx.moveTo(-L * 1.25, 0); ctx.lineTo(L * 0.8, 0); ctx.stroke();
            ctx.restore();
        }
        function firefly(p, t) {
            p.vx += (Math.random() - 0.5) * 0.04 * dpr;
            p.vy += (Math.random() - 0.5) * 0.04 * dpr;
            const max = 0.45 * dpr;
            p.vx = Math.max(-max, Math.min(max, p.vx));
            p.vy = Math.max(-max, Math.min(max, p.vy));
            p.x = (p.x + p.vx + W) % W;
            p.y = (p.y + p.vy + H) % H;
            const glow = 0.25 + 0.75 * Math.pow((Math.sin(t * 0.0016 * p.sp + p.ph) + 1) / 2, 3);
            const r = 2.2 * p.s;
            const g = ctx.createRadialGradient(p.x, p.y, 0, p.x, p.y, r * 7);
            g.addColorStop(0, `rgba(190, 255, 170, ${0.9 * glow})`);
            g.addColorStop(0.18, `rgba(110, 231, 154, ${0.45 * glow})`);
            g.addColorStop(1, "rgba(74, 222, 128, 0)");
            ctx.fillStyle = g;
            ctx.beginPath(); ctx.arc(p.x, p.y, r * 7, 0, Math.PI * 2); ctx.fill();
        }
        (function frame(t) {
            requestAnimationFrame(frame);
            if (document.hidden) return;
            ctx.clearRect(0, 0, W, H);
            const dark = root.getAttribute("data-theme") === "dark";
            for (const p of parts) dark ? firefly(p, t) : leaf(p, t);
        })(0);
    })();

